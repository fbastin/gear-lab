// French typography: non-breaking space before : and %, and inside « ».
const frTypo = s => String(s).replace(/ ([:%$»])/g, ' $1').replace(/« /g, '« ');

function T(key, ...args) {
  let v = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.en[key];
  if (v === undefined) return key;
  if (typeof v === 'function') v = v(...args);
  return lang === 'fr' ? frTypo(v) : v;
}
// Picks the current language from a { en, fr } object.
function tr(o) {
  if (!o || typeof o !== 'object') return o;
  const v = o[lang] ?? o.en;
  return lang === 'fr' ? frTypo(v) : v;
}
const num = (x, d) => (lang === 'fr' ? x.toFixed(d).replace('.', ',') : x.toFixed(d));
const pct = p => (lang === 'fr' ? `${p} %` : `${p}%`);

function setLang(l) {
  lang = l;
  try { localStorage.setItem('gearlab-lang', l); } catch (e) { /* storage blocked */ }
  applyStatic();
}
function applyStatic() {
  document.documentElement.lang = lang;
  document.title = T('doc_title');
  const md = document.querySelector('meta[name=description]'); if (md) md.content = T('desc');
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = T(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => el.setAttribute('aria-label', T(el.dataset.i18nAria)));
  document.querySelectorAll('[data-href]').forEach(el => { el.href = el.dataset.href.replace('{lang}', lang); });
  const lb = document.getElementById('langBtn');
  lb.textContent = T('lang_btn'); lb.setAttribute('aria-label', T('lang_label')); lb.title = T('lang_label');
}
